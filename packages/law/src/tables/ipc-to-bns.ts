/**
 * IPC section -> BNS section(s), for the sections in the IPC table.
 * "split": the IPC section is spread over several BNS provisions.
 * "merged": several IPC sections land in one BNS provision.
 * "dropped": no BNS counterpart.
 */
export interface IpcBnsMapping {
  ipc: string;
  bns: string[];
  relation: "one-to-one" | "split" | "merged" | "dropped";
  note?: string;
}

const m = (ipc: string, bns: string | string[], relation: IpcBnsMapping["relation"] = "one-to-one", note?: string): IpcBnsMapping => ({
  ipc,
  bns: Array.isArray(bns) ? bns : [bns],
  relation,
  ...(note ? { note } : {})
});

